int saac_jpeg_has_dht(const uint8_t *p, size_t len)
{
    if (!p || len < 4 || p[0] != 0xFF || p[1] != 0xD8) return -1;
    size_t i = 2;
    int found = 0;
    while (i + 1 < len) {
        if (p[i] != 0xFF) return -1;
        while (i < len && p[i] == 0xFF) i++;         /* fill bytes before a marker */
        if (i >= len) return -1;
        uint8_t m = p[i++];
        if (m == 0xDA) return found;                  /* SOS: the tables come before it */
        if (m == 0x01 || (m >= 0xD0 && m <= 0xD7)) continue;   /* markers without a length */
        if (m == 0xD9 || i + 2 > len) return -1;
        size_t seg = ((size_t)p[i] << 8) | p[i + 1];
        if (seg < 2 || i + seg > len) return -1;
        if (m == 0xC4) found = 1;
        i += seg;
    }
    return -1;
}

size_t saac_jpeg_insert_dht(const uint8_t *jpeg, size_t len, uint8_t *out)
{
    memcpy(out, jpeg, 2);                             /* SOI */
    memcpy(out + 2, dht, sizeof dht);
    memcpy(out + 2 + sizeof dht, jpeg + 2, len - 2);
    return len + sizeof dht;
}

size_t saac_jpeg_end(const uint8_t *p, size_t len)
{
    if (!p || len < 4 || p[0] != 0xFF || p[1] != 0xD8) return 0;
    size_t i = 2;
    int scan = 0;                                     /* inside entropy-coded data */
    while (i + 1 < len) {
        if (scan) {
            /* entropy-coded data holds FF only as FF00 or a restart marker */
            const uint8_t *ff = memchr(p + i, 0xFF, len - i);
            if (!ff) return 0;
            i = (size_t)(ff - p);
            if (i + 1 >= len) return 0;
            uint8_t m = p[i + 1];
            if (m == 0x00 || (m >= 0xD0 && m <= 0xD7)) {
                i += 2;
                continue;
            }
            scan = 0;                                 /* a marker: EOI, or a progressive frame's next segment */
        }
        if (p[i] != 0xFF) return 0;
        while (i < len && p[i] == 0xFF) i++;          /* fill bytes before a marker */
        if (i >= len) return 0;
        uint8_t m = p[i++];
        if (m == 0xD9) return i;                      /* EOI */
        if (m == 0x01 || (m >= 0xD0 && m <= 0xD7)) continue;
        if (m == 0xD8 || i + 2 > len) return 0;
        size_t seg = ((size_t)p[i] << 8) | p[i + 1];
        if (seg < 2 || i + seg > len) return 0;
        i += seg;
        if (m == 0xDA) scan = 1;                      /* SOS: its entropy-coded data follows */
    }
    return 0;
}
